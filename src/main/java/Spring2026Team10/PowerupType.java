package Spring2026Team10;

/**
 * Represents the different types of powerups available in the game.
 * Each powerup provides a unique beneficial effect to help the player escape.
 */
public enum PowerupType {
    /** Grants the player a temporary movement speed boost. */
    COFFEE,
    /** Temporarily freezes all guards on the map. */
    SNOWFLAKE,
    /** Restores one lost life to the player. */
    DOCTORS_NOTE
}